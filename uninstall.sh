#!/usr/bin/env bash
# Remove the codeprint launcher and the project's virtual environment.
# Your screenshots, pages and config are KEPT unless you pass --purge-data.
#   ./uninstall.sh [--bin-dir DIR] [--purge-data] [--yes]
set -euo pipefail
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN_DIR="${HOME}/.local/bin"
PURGE=0; ASSUME_YES=0
MARKER="# codeprint-launcher (generated by install.sh)"
while [ $# -gt 0 ]; do
    case "$1" in
        --bin-dir) BIN_DIR="${2:?}"; shift ;;
        --purge-data) PURGE=1 ;;
        --yes|-y) ASSUME_YES=1 ;;
        -h|--help) sed -n '2,4p' "$0"; exit 0 ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
    shift
done

LAUNCHER="$BIN_DIR/codeprint"
if [ -e "$LAUNCHER" ] && grep -qF "$MARKER" "$LAUNCHER"; then
    rm -f "$LAUNCHER"; echo "Removed $LAUNCHER"
elif [ -e "$LAUNCHER" ]; then
    echo "Not removing $LAUNCHER: it was not created by CodePrint."
else
    echo "No launcher at $LAUNCHER"
fi

if [ -d "$PROJECT_DIR/.venv" ]; then
    rm -rf "$PROJECT_DIR/.venv"; echo "Removed $PROJECT_DIR/.venv"
fi

DATA_DIR="${CODEPRINT_DATA_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/codeprint}"
CONF_DIR="${CODEPRINT_CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/codeprint}"
if [ "$PURGE" -eq 1 ]; then
    for d in "$DATA_DIR" "$CONF_DIR"; do
        # safety: only ever delete a directory literally named "codeprint" (or the explicit env override)
        case "$(basename "$d")" in codeprint) ;; *)
            [ -n "${CODEPRINT_DATA_DIR:-}${CODEPRINT_CONFIG_DIR:-}" ] || { echo "Refusing to delete $d"; continue; } ;;
        esac
        [ "$d" != "$HOME" ] && [ "$d" != "/" ] && [ -d "$d" ] || continue
        if [ "$ASSUME_YES" -ne 1 ]; then
            read -r -p "Permanently delete $d ? Type 'yes' to confirm: " ans
            [ "$ans" = "yes" ] || { echo "Kept $d"; continue; }
        fi
        rm -rf -- "$d"; echo "Deleted $d"
    done
else
    echo "Kept your data ($DATA_DIR) and config ($CONF_DIR). Use --purge-data to delete them."
fi
