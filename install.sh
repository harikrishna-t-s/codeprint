#!/usr/bin/env bash
# CodePrint installer: user-local, no sudo, never edits your shell config.
#   ./install.sh [--no-browser] [--bin-dir DIR]
set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENV_DIR="$PROJECT_DIR/.venv"
BIN_DIR="${HOME}/.local/bin"
INSTALL_BROWSER=1
MARKER="# codeprint-launcher (generated by install.sh)"

while [ $# -gt 0 ]; do
    case "$1" in
        --no-browser) INSTALL_BROWSER=0 ;;
        --bin-dir) BIN_DIR="${2:?--bin-dir needs a directory}"; shift ;;
        -h|--help) sed -n '2,3p' "$0"; exit 0 ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
    shift
done

say() { printf '\033[1m==>\033[0m %s\n' "$*"; }
die() { echo "ERROR: $*" >&2; exit 1; }

say "Checking prerequisites"
command -v python3 >/dev/null || die "python3 not found (Ubuntu: sudo apt install python3 python3-venv)"
python3 - <<'PY' || die "Python 3.9 or newer is required"
import sys; sys.exit(0 if sys.version_info >= (3, 9) else 1)
PY
python3 -c 'import venv, ensurepip' 2>/dev/null || die "python3-venv is missing (Ubuntu: sudo apt install python3-venv)"
if command -v fc-list >/dev/null; then
    fonts="$(fc-list 2>/dev/null || true)"        # (grep -q in a pipe + pipefail gave a false warning)
    case "${fonts,,}" in
        *mono*) ;;
        *) echo "note: no monospace font detected; install one: sudo apt install fonts-dejavu-core" ;;
    esac
fi

say "Creating data/config directories"
DATA_DIR="${CODEPRINT_DATA_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/codeprint}"
CONF_DIR="${CODEPRINT_CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/codeprint}"
mkdir -p "$DATA_DIR" "$CONF_DIR" "$BIN_DIR"

say "Creating virtual environment: $VENV_DIR"
[ -x "$VENV_DIR/bin/python" ] || python3 -m venv "$VENV_DIR" || die "could not create the virtual environment"

say "Installing Python dependencies"
"$VENV_DIR/bin/python" -m pip install --quiet --upgrade pip || echo "warning: could not upgrade pip (continuing)"
"$VENV_DIR/bin/python" -m pip install --quiet -r "$PROJECT_DIR/requirements.txt" \
    || die "pip install failed (check your network connection)"

if [ "$INSTALL_BROWSER" -eq 1 ]; then
    say "Installing Chromium for Playwright (optional; ~150 MB download)"
    if "$VENV_DIR/bin/python" -m playwright install chromium; then
        echo "Chromium installed. If rendering later fails with missing libraries, run (needs sudo):"
        echo "    $VENV_DIR/bin/python -m playwright install-deps chromium"
    else
        echo "warning: Chromium download failed. codeprint still works: it falls back to the built-in Pillow renderer."
    fi
else
    echo "Skipping browser install (--no-browser): the Pillow renderer will be used."
fi

say "Installing the 'codeprint' command into $BIN_DIR"
LAUNCHER="$BIN_DIR/codeprint"
if [ -e "$LAUNCHER" ] && ! grep -qF "$MARKER" "$LAUNCHER" 2>/dev/null; then
    die "$LAUNCHER already exists and was not created by CodePrint; remove it or use --bin-dir"
fi
cat > "$LAUNCHER" <<LAUNCH
#!/bin/sh
$MARKER
# project: $PROJECT_DIR
exec "$VENV_DIR/bin/python" "$PROJECT_DIR/codeprint.py" "\$@"
LAUNCH
chmod +x "$LAUNCHER"

case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) echo
       echo "NOTE: $BIN_DIR is not on your PATH. Add this line to your shell profile yourself if you want:"
       echo "    export PATH=\"$BIN_DIR:\$PATH\""
       echo "(this installer does not touch your shell configuration)" ;;
esac

echo
say "Installed. Next: ./setup.sh   (then: codeprint doctor)"
